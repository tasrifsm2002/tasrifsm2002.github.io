Write-Host "Target repository: $Repo" -ForegroundColor Cyan

if (-not (Test-Path -LiteralPath $Repo -PathType Container)) {
    throw "Repository folder not found: $Repo"
}

$GitDir = Join-Path $Repo ".git"
if (-not (Test-Path -LiteralPath $GitDir)) {
    throw "The .git folder was not found. This does not look like a Git working repository. Nothing was deleted."
}

$ResolvedRepo = (Resolve-Path -LiteralPath $Repo).Path
$ToDelete = @()
$Missing = 0

foreach ($RelativePath in $StrayFiles) {
    $Candidate = Join-Path $ResolvedRepo $RelativePath
    $FullCandidate = [System.IO.Path]::GetFullPath($Candidate)

    # Safety: every target must remain inside the repository and must never be .git.
    if (-not $FullCandidate.StartsWith($ResolvedRepo + [System.IO.Path]::DirectorySeparatorChar, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw "Unsafe path outside repository detected: $RelativePath"
    }
    if ($FullCandidate -match '[\\/]\.git([\\/]|$)') {
        throw "Refusing to touch .git: $RelativePath"
    }

    if (Test-Path -LiteralPath $FullCandidate) {
        $ToDelete += [PSCustomObject]@{ Relative = $RelativePath; Full = $FullCandidate }
    } else {
        $Missing++
    }
}

Write-Host ""
Write-Host ("Listed paths: {0} | Found: {1} | Already missing: {2}" -f $StrayFiles.Count, $ToDelete.Count, $Missing) -ForegroundColor Yellow
Write-Host ""
Write-Host "The following listed paths will be deleted:" -ForegroundColor Yellow
$ToDelete | ForEach-Object { Write-Host ("  " + $_.Relative) }

Write-Host ""
$Confirm = Read-Host "Type DELETE to remove only these listed paths"
if ($Confirm -cne "DELETE") {
    Write-Host "Cancelled. Nothing was deleted." -ForegroundColor Cyan
    exit 0
}

foreach ($Item in $ToDelete) {
    Remove-Item -LiteralPath $Item.Full -Recurse -Force
}

Write-Host ""
Write-Host ("Cleanup complete. Deleted {0} listed paths. The .git folder was not touched." -f $ToDelete.Count) -ForegroundColor Green
Write-Host "Now review the changes in GitHub Desktop before committing."
